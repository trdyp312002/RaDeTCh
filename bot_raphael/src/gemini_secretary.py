import google.generativeai as genai
from PIL import Image
import json
import io

class GeminiSecretary:
    def __init__(self, api_key):
        """
        เตรียมใช้งานโมเดล Gemini สำหรับการเป็นเลขาส่วนตัว 'ราฟาเอล' (Raphael)
        """
        genai.configure(api_key=api_key)
        # ใช้ gemini-2.5-flash สำหรับความรวดเร็วและฉลาดในการวิเคราะห์
        self.model = genai.GenerativeModel('gemini-2.5-flash')


    def analyze_image(self, image_bytes):
        """
        วิเคราะห์รูปภาพโดยใช้ Multimodal Vision (รองรับหน้าปกหนังสือและข้อมูลสุขภาพ)
        """
        try:
            img = Image.open(io.BytesIO(image_bytes))
            
            prompt = """
            วิเคราะห์รูปภาพนี้ กรุณาระบุว่ารูปภาพนี้คืออะไรระหว่าง:
            1. หน้าปกหนังสือ (Book Cover)
            2. ข้อมูลสุขภาพ/การออกกำลังกาย (Health Data เช่น หน้าปัดเครื่องชั่งน้ำหนัก, นาฬิกาสมาร์ทวอทช์, แอปสุขภาพ)
            
            ส่งผลลัพธ์กลับมาในรูปแบบ JSON เท่านั้น (ห้ามมีข้อความอธิบายใดๆ เพิ่มเติมเด็ดขาด)
            
            หากเป็น 'หน้าปกหนังสือ' ให้ใช้โครงสร้างนี้:
            {
                "type": "book",
                "title": "ชื่อหนังสือที่เป็นทางการ",
                "author": "ชื่อผู้เขียน/ผู้แต่ง",
                "desc": "คำโปรย/สรุปแนวคิดหลัก 1-2 ประโยค",
                "category": "หมวดหมู่แบบลำดับขั้น (เช่น การเงิน/การลงทุน/หุ้น)"
            }
            
            หากเป็น 'ข้อมูลสุขภาพ' ให้ใช้โครงสร้างนี้:
            {
                "type": "health",
                "weight": ตัวเลขน้ำหนัก (kg) หรือ null,
                "sleep_hours": ตัวเลขชั่วโมงการนอน หรือ null,
                "calories_in": ตัวเลขแคลอรี่ที่กิน หรือ null,
                "calories_out": ตัวเลขแคลอรี่ที่เผาผลาญ หรือ null,
                "notes": "สรุปสั้นๆ ว่าในรูปมีข้อมูลอะไรบ้าง"
            }
            """
            
            response = self.model.generate_content([prompt, img])
            text_response = response.text.strip()
            
            import re
            match = re.search(r'```(?:json)?\s*(\{.*?\})\s*```', text_response, re.DOTALL)
            if match:
                text_response = match.group(1)
            else:
                text_response = text_response.strip('` \n')
                if text_response.startswith("json"):
                    text_response = text_response[4:].strip()
                
            data = json.loads(text_response.strip())
            return data
            
        except Exception as e:
            print(f"[ERROR] เกิดข้อผิดพลาดในการวิเคราะห์รูปภาพด้วย AI: {e}", flush=True)
            return {
                "error": True,
                "message": f"ไม่สามารถวิเคราะห์รูปภาพได้เนื่องจาก: {str(e)}"
            }

    def chat(self, prompt, user_name="นายท่าน", context_info=None):
        """
        โต้ตอบบทสนทนากับผู้ใช้งานในฐานะราฟาเอล เลขาส่วนตัวสุดนอบน้อม
        :param prompt: คำถามหรือคำพูดของนายท่าน
        :param user_name: ชื่อของผู้ใช้
        :param context_info: ข้อมูลบริบทเพิ่มเติม (เช่น รายการที่ต้องทำ ตารางรูทีน หรือวันหยุด) เพื่อให้บอทฉลาดขึ้น
        :return: ข้อความคำตอบสุดหรูหราและนอบน้อมจากราฟาเอล
        """
        try:
            # เอกลักษณ์เฉพาะของราฟาเอล
            system_instruction = (
                "คุณคือ 'ราฟาเอล' (Raphael) AI เลขาส่วนตัวอัจฉริยะที่ดูแลชีวิตประจำวันของนายท่านอย่างใกล้ชิด\n"
                "บุคลิกของคุณคือ: สง่างาม, สุภาพนอบน้อมอย่างที่สุด, ซื่อสัตย์, อบอุ่น, และมีความกระตือรือร้นที่จะช่วยเหลือ\n"
                "สรรพนามเรียกผู้ใช้: 'นายท่าน', 'คุณท่าน', 'ท่าน [ชื่อผู้ใช้]'\n"
                "สรรพนามแทนตัวคุณ: 'กระผม', 'ราฟาเอล'\n"
                "คำลงท้ายที่ต้องใช้เสมอ: 'ครับกระผม', 'ครับคุณท่าน', 'อย่างยิ่งครับ'\n"
                "จงตอบกลับด้วยภาษาไทยที่สละสลวย สุภาพระดับสูงสุด (เหมือนพ่อบ้านหรือเลขาฯ ส่วนตัวระดับเอ็กเซกคิวทีฟในคฤหาสน์หรู)\n\n"
                
                "=== [หน้าที่พิเศษ: การนำข้อมูลไปบันทึกในระบบของเว็บไซต์] ===\n"
                "หากนายท่านมีคำสั่งให้ทำการ 'บันทึก', 'เพิ่ม', 'จดบันทึกสิ่งใหม่ลงในเว็บ' (เช่น เพิ่มเพลง, เพิ่มอาหาร/เมนูอาหาร, บันทึกหนังสือที่ควรอ่าน, เพิ่มสถานที่ท่องเที่ยว)\n"
                "คุณจะต้องตอบรับอย่างนอบน้อมว่าจะดำเนินการให้ทันที และแนบรูปแบบคำสั่งพิเศษ (Action Schema) ไว้ที่ 'บรรทัดท้ายสุด' ของคำตอบเสมอ เพื่อให้โปรแกรมเบื้องหลังทำงาน\n"
                "รูปแบบคำสั่งพิเศษที่ต้องแนบไว้ที่บรรทัดท้ายสุด (ห้ามลบ ห้ามแก้ฟอร์แมตเด็ดขาด):\n"
                
                "1. บันทึกเมนูอาหารลงในเว็บไซต์:\n"
                "[[SAVE_ACTION: {\"type\": \"menu\", \"name\": \"ชื่ออาหาร\", \"desc\": \"คำอธิบายสั้นๆ\", \"calories\": 520, \"time\": 15, \"nationality\": \"thai/japanese/korean/western\"}]]\n"
                
                "2. บันทึกเพลงลงในเว็บไซต์:\n"
                "[[SAVE_ACTION: {\"type\": \"music\", \"lang\": \"japanese/korean/thai/english\", \"artist\": \"ชื่อศิลปิน\", \"title\": \"ชื่อเพลง\", \"url\": \"ลิงก์เพลงจาก youtube หรือ youtube music\", \"duration\": 210}]]\n"
                
                "3. บันทึกสถานที่ท่องเที่ยวลงในเว็บไซต์:\n"
                "[[SAVE_ACTION: {\"type\": \"travel\", \"name\": \"ชื่อสถานที่\", \"desc\": \"รายละเอียด\", \"region\": \"toyama/japan/world\", \"name_jp\": \"ชื่อภาษาญี่ปุ่น (หากมี)\"}]]\n"
                
                "4. บันทึกหนังสือที่ควรอ่านลงในเว็บไซต์:\n"
                "[[SAVE_ACTION: {\"type\": \"book\", \"title\": \"ชื่อหนังสือ\", \"author\": \"ผู้แต่ง\", \"desc\": \"เรื่องย่อ/เหตุผลที่ควรอ่าน\", \"category\": \"หมวดหมู่ของหนังสือที่จัดลำดับขั้นคั่นด้วยเครื่องหมาย '/' (เช่น 'การเรียน/ภาษา/ภาษาอังกฤษ', 'การเงิน/การลงทุน/หุ้น', 'พัฒนาตนเอง/จิตวิทยา/ความคิด') ให้ตรงกับแนวเนื้อหาของเล่มที่สุด\"}]]\n\n"
                
                "ตัวอย่างเช่น หากนายท่านบอกว่า 'ราฟาเอล เพิ่มหนังสือ The Psychology of Money ของ Morgan Housel ลงเว็บให้หน่อย' คุณจะตอบว่า:\n"
                "'รับทราบครับคุณท่าน กระผมจะทำการบันทึกหนังสือ \"The Psychology of Money\" แต่งโดยคุณ \"Morgan Housel\" ลงในระบบเว็บไซต์พอร์ตโฟลิโอของคุณท่านเรียบร้อยแล้วครับกระผม!\n"
                "[[SAVE_ACTION: {\"type\": \"book\", \"title\": \"The Psychology of Money\", \"author\": \"Morgan Housel\", \"desc\": \"หนังสือการเงินที่มุ่งอธิบายพฤติกรรมมนุษย์\", \"category\": \"การเงิน/การลงทุน/จิตวิทยาการเงิน\"}]]'\n"
            )

            # ใส่ข้อมูลบริบทปัจจุบัน (Context) เพื่อความฉลาดล้ำลึก
            context_str = ""
            if context_info:
                context_str = "\n[ข้อมูลบริบทปัจจุบันของคุณท่านสำหรับประกอบการตอบคำถาม]:\n"
                for key, val in context_info.items():
                    context_str += f"- {key}: {val}\n"
                context_str += "\n(กรุณาใช้ข้อมูลข้างต้นตอบนายท่านอย่างเป็นธรรมชาติและชาญฉลาดที่สุด)\n"

            full_prompt = (
                f"{system_instruction}"
                f"{context_str}\n"
                f"นายท่าน {user_name} กล่าวว่า: \"{prompt}\"\n\n"
                f"คำตอบจากราฟาเอล:"
            )
            
            response = self.model.generate_content(full_prompt)
            return response.text.strip()
            
        except Exception as e:
            print(f"[ERROR] เกิดข้อผิดพลาดในการทำงานของราฟาเอล: {e}", flush=True)
            return f"🛡️ ขออภัยเป็นอย่างยิ่งครับคุณท่าน พอดีวงจรสมองกลของกระผมเกิดข้อขัดข้องเล็กน้อย: {str(e)} ขออภัยในความไม่สะดวกครับกระผม"
